#include <unistd.h>

void	ft_print_comb(void)
{
	int	a;
	int	b;
	int	c;

	a = 48;
	while (a <= '0' + 7)
	{
		b = a + 1;
		while (b <= '0' + 8)
		{
			c = b + 1;
			while (c <= '0' + 9)
			{
				write(1, &a, 1);
				write(1, &b, 1);
				write(1, &c, 1);
				if (a != '0' + 7 || b != '0' + 8 || c != '0' + 9)
					write(1, ", ", 2);
				c++;
			}
			b++;
		}
		a++;
	}
}
