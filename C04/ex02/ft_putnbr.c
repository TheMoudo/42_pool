#include <unistd.h>

void	put_char(char c)
{
	write(1, &c, 1);
}

void	ft_putnbr(int nb)
{
	char	tab[10];
	int		i;

	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = -nb;
	}
	i = 0;
	while (nb >= 10)
	{
		tab[i] = (nb % 10) + '0';
		nb = nb / 10;
		i++;
	}
	tab[i] = nb + '0';
	while (i >= 0)
		put_char(tab[i--]);
}
